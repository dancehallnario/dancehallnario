    const stepDetail =
        document.getElementById(
            "stepDetail"
        );



    // ==================================================
    // IMAGEN
    // ==================================================

    let imageHTML = "";

    if (step.image) {

        imageHTML = `

            <img
                class="step-image"
                src="${step.image}"
                alt="Paso de Dancehall ${step.name}"
            >

        `;

    }



    // ==================================================
    // CREADOR
    // ==================================================

