const alphabet =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ";

const alphabetContainer =
    document.getElementById("alphabet");

const stepsList =
    document.getElementById("stepsList");

const searchInput =
    document.getElementById("searchInput");

const searchResults =
    document.getElementById("searchResults");



// ======================================================
// CREAR LETRAS A-Z
// ======================================================

for (let letter of alphabet) {

    const button =
        document.createElement("button");

    button.textContent =
        letter;

    button.classList.add(
        "letter-button"
    );

    button.addEventListener(
        "click",
        function() {

            showSteps(letter);

        }
    );

    alphabetContainer.appendChild(
        button
    );

}



// ======================================================
// MOSTRAR PASOS POR LETRA
// ======================================================

function showSteps(letter) {

    const filteredSteps =
        steps.filter(function(step) {

            return step.letter === letter;

        });


    stepsList.innerHTML = "";


    document.getElementById(
        "stepDetail"
    ).innerHTML = "";


    if (filteredSteps.length === 0) {

        stepsList.innerHTML =
            "<p>No hay pasos registrados con esta letra.</p>";

        return;
    }


    filteredSteps.forEach(
        function(step) {

            const stepElement =
                document.createElement("button");

            stepElement.textContent =
                step.name;

            stepElement.classList.add(
                "step-button"
            );


            stepElement.addEventListener(
                "click",
                function() {

                    showStepDetail(step);

                }
            );


            stepsList.appendChild(
                stepElement
            );

        }
    );


    stepsList.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });

}



// ======================================================
// NORMALIZAR TEXTO
// Permite buscar sin importar mayúsculas o tildes
// ======================================================

function normalizeText(text) {

    return text
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "");

}



// ======================================================
// BUSCADOR
// ======================================================

searchInput.addEventListener(
    "input",
    function() {

        const query =
            normalizeText(
                searchInput.value.trim()
            );


        searchResults.innerHTML = "";


        if (!query) {

            return;

        }


        const results =
            steps.filter(function(step) {

                return normalizeText(
                    step.name
                ).includes(query);

            });


        if (results.length === 0) {

            searchResults.innerHTML = `

                <div class="search-empty">

                    No encontramos un paso con ese nombre.

                </div>

            `;

            return;

        }


        results.forEach(
            function(step) {

                const result =
                    document.createElement(
                        "button"
                    );


                result.classList.add(
                    "search-result"
                );


                result.textContent =
                    step.name;


                result.addEventListener(
                    "click",
                    function() {

                        showStepDetail(step);

                    }
                );


                searchResults.appendChild(
                    result
                );

            }
        );

    }
);



